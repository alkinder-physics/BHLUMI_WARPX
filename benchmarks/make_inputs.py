def from_template(base_path, overrides=None, remove_prefixes=()):
    """Text of `base_path` with keys replaced (or appended if absent) and keys starting with any of
    `remove_prefixes` dropped. Comments and order are kept."""
    overrides = dict(overrides or {})
    done, out = set(), []
    for raw in open(base_path):
        line = raw.rstrip("\n")
        body = line.split("#", 1)[0]
        if "=" in body:
            key = body.split("=", 1)[0].strip()
            if any(key.startswith(pr) for pr in remove_prefixes):
                continue
            if key in overrides:
                indent = line[: len(line) - len(line.lstrip())]
                out.append(f"{indent}{key} = {overrides[key]}")
                done.add(key)
                continue
        out.append(line)
    extra = [k for k in overrides if k not in done]
    if extra:
        out.append("# ---- added by make_inputs.from_template")
        out += [f"{k} = {overrides[k]}" for k in extra]
    return "\n".join(out) + "\n"


def write(text, path):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    return path


def _fmt(v):
    """Short file-name tag for a value: 2e+10 -> 2e10, "15e-3" -> 0.015, "0." -> 0."""
    try:
        v = f"{float(v):g}"
    except (TypeError, ValueError):
        v = str(v)
    return v.replace("+", "").replace("/", "-").replace(" ", "")


def scan(grid, outdir, base=None, fixed=None, remove_prefixes=(), name="inputs", summary=None):
    """One input file per point of `grid` (dict: key -> list of values) and outdir/manifest.csv.

    base=None: keys are headon_round_inputs parameters (see HEADON_DEFAULTS); `fixed` sets the others.
    base=<path>: keys are WarpX input keys (e.g. "my_constants.npart"), applied with from_template.
    summary(path) -> dict: optional extra manifest columns computed from each written file.
    """
    keys = list(grid)
    rows = []
    for values in itertools.product(*(grid[k] for k in keys)):
        point = dict(zip(keys, values))
        tag = "_".join(f"{k.split('.')[-1]}{_fmt(v)}" for k, v in point.items()) or "base"
        path = os.path.join(outdir, f"{name}_{tag}.txt")
        if base is None:
            text = headon_round_inputs({**(fixed or {}), **point})
        else:
            text = from_template(base, {**(fixed or {}), **point}, remove_prefixes)
        write(text, path)
        row = {"file": os.path.relpath(path, outdir), **point}
        if summary:
            row.update(summary(path))
        rows.append(row)
    cols = list(dict.fromkeys(k for r in rows for k in r))
    with open(os.path.join(outdir, "manifest.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader(); w.writerows(rows)
    return rows


