"""
make_inputs.py -- write WarpX input templates for wx_bhabha.py.

Two ways to make inputs:

1. headon_round_inputs(params): the analytic benchmark (round, head-on, rigid, no QED, no external fields).
   Every physical number is a my_constants line built from `params`, so you can also edit the written file
   by hand: bhabha_theory.Params reads the theory inputs back from the file itself.

2. from_template(base, overrides, remove_prefixes): any existing input file (e.g. the FCC box scan) with
   keys replaced, added or removed -- for scans over the real configuration.

scan(...) writes one file per point of a parameter grid plus a manifest.csv.
"""
import csv
import itertools
import os

HEADON_DEFAULTS = {
    "E_GeV": 45.6,          # beam energy
    "npart": 2.0e10,        # particles per bunch
    "nmacropart": 4e6,      # macroparticles per bunch
    "sigma_um": 10.0,       # round beams: sigma_x = sigma_y
    "sigmaz_mm": 1.0,
    "cut_sigmas": 4,        # Gaussian cut in x, y, z (WarpX x_cut, y_cut, z_cut)
    "box_xy_sigmas": 60,    # full transverse box width in units of sigma (+-30 sigma)
    "box_z_sigmas": 16,     # full box length in units of sigma_z (>= 4 * cut_sigmas: bunches start touching)
    "nx": 512, "ny": 512, "nz": 1024,   # nz: cutoff length 2 sqrt(3) sigma / theta >= 10 dz up to 120 mrad
    "beta_sampler_m": 1e9,  # beta* seen by wx_bhabha.py's vertex sampler: effectively no hourglass
}


